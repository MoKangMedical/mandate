他五次巡游天下——不是微服私访，而是带着庞大仪仗。途中在泰山封禅（祭天告地），在琅琊台刻石纪功长达三个月，在湘山遇大风迁怒山神砍光山上树木。

公元前210年，嬴政第五次巡游途中在沙丘（今河北广宗）病逝，享年四十九岁。

